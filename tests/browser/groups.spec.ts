test('unsent group messages survive cancelled navigation and are discarded before an account switch',async({page})=>{
 await page.goto('/portal.html');await preview(page,'learner');
 await page.getByRole('button',{name:'Open Learning together',exact:true}).click();
 await page.getByLabel('Your discussion message',{exact:true}).fill('UNSENT_GROUP_MESSAGE');
 page.once('dialog',dialog=>dialog.dismiss());
 await navigation(page).getByRole('button',{name:'Courses',exact:true}).click();
 await expect(page.getByLabel('Your discussion message',{exact:true})).toHaveValue('UNSENT_GROUP_MESSAGE');
 page.once('dialog',dialog=>dialog.accept());
 await page.getByRole('region',{name:'Demo account controls'}).getByRole('button',{name:'Preview admin',exact:true}).click();
 await navigation(page).getByRole('button',{name:'Study groups',exact:true}).click();
 await page.getByRole('button',{name:'Open Learning together',exact:true}).click();
 await expect(page.getByLabel('Your discussion message',{exact:true})).toHaveValue('');
 expect(await page.locator('.group-workspace').innerText()).not.toContain('UNSENT_GROUP_MESSAGE');
});

test('an administrator publishes an attached document and learners download only by choice',async({page})=>{
 const document=Buffer.from('%PDF-1.7\nA synthetic original study handout.\n%%EOF');
 await page.goto('/portal.html');await preview(page,'admin');
 await navigation(page).getByRole('button',{name:'New course',exact:true}).click();
 await page.getByLabel('Course title',{exact:true}).fill('Read a study handout');
 await page.getByLabel('Course purpose',{exact:true}).fill('Download one short handout and explain its main idea.');
 await page.getByLabel('Lesson 1 title',{exact:true}).fill('One small handout');
 await page.getByLabel('Lesson 1 upload file',{exact:true}).setInputFiles({name:'original-study.pdf',mimeType:'application/pdf',buffer:document});
 await expect(page.getByRole('button',{name:'Remove file from lesson 1',exact:true})).toBeVisible();
 await expect(page.getByRole('combobox',{name:'Lesson 1 material type',exact:true})).toHaveValue('document');
 await page.getByLabel('Lesson 1 creator or source credit',{exact:true}).fill('Original test educator');
 await page.getByLabel('Lesson 1 content rights').fill('Original material under CC BY 4.0.');
 await page.getByLabel('I reviewed the text, source credits and permission to publish each lesson.',{exact:true}).check();
 await page.getByRole('button',{name:'Publish course',exact:true}).click();
 await expect(page.getByRole('status').filter({hasText:'Your reviewed course is published.'})).toBeVisible();
 await page.getByRole('button',{name:'Close editor',exact:true}).click();
 await page.getByRole('region',{name:'Demo account controls'}).getByRole('button',{name:'Preview learner',exact:true}).click();
 await page.getByRole('button',{name:'Explore Read a study handout',exact:true}).click();
 await expect(page.getByRole('button',{name:'Download original-study.pdf',exact:true})).toBeVisible();
 await expect(page.locator('iframe,video,audio,embed,object')).toHaveCount(0);
 const downloadEvent=page.waitForEvent('download');
 await page.getByRole('button',{name:'Download original-study.pdf',exact:true}).click();
 const download=await downloadEvent;
 expect(download.suggestedFilename()).toBe('original-study.pdf');
 const stream=await download.createReadStream(),chunks:Buffer[]=[];
 if(!stream)throw new Error('The selected download did not produce a readable file.');
 for await(const chunk of stream)chunks.push(Buffer.from(chunk));
 expect(Buffer.concat(chunks)).toEqual(document);
});
